
//6.	Write an infinite loop using do while condition
import java.util.*;

public class infiniteloopusingdowhile {
    public static void main(String args[]) {
        int i;
        i = 1;
        do {
            System.out.println(i + "  Vaibhav & Suraj");
            i++;
        } while (i <= i);

    }
}